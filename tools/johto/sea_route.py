def wild():
    p = os.path.join(REPO, 'src/data/wild_encounters.json'); wj = json.load(open(p))
    grp = next(g for g in wj['wild_encounter_groups']
               if any(e.get('base_label', '').startswith('sRoute21South_') for e in g.get('encounters', [])))
    enc = grp['encounters']
    ids = {mid(n) for n in MAPS}
    enc[:] = [e for e in enc if e.get('map') not in ids]
    mons = lambda t: [{'min_level': a, 'max_level': b, 'species': 'SPECIES_' + s} for s, a, b in t]
    for n in MAPS:
        for ver in ('FireRed', 'LeafGreen'):
            enc.append({'map': mid(n), 'base_label': 's%s_%s' % (n, ver),
                        'water_mons': {'encounter_rate': 4, 'mons': mons(WATER_MONS)},
                        'fishing_mons': {'encounter_rate': 20, 'mons': mons(FISH_MONS)}})
    open(p, 'w').write(json.dumps(wj, indent=2, ensure_ascii=False) + '\n')

def reach(grids):
    """BFS over passable cells across our maps + the seams, from one seam cell per sea system."""
    starts = []
    for m, d, o in SEEDS:
        g = grids[m]; w, h = len(g[0]), len(g)
        cells = [((0 if d == 'left' else w - 1), y) for y in range(h)] if d in ('left', 'right') else \
                [(x, (0 if d == 'up' else h - 1)) for x in range(w)]
        ok = [c for c in cells if passable(g[c[1]][c[0]])]
        starts.append((m,) + ok[len(ok) // 2])
    seen, q = set(starts), collections.deque(starts)
    while q:
        m, x, y = q.popleft(); gg = grids[m]; w, h = len(gg[0]), len(gg)
        for dx, dy, d in ((1, 0, 'right'), (-1, 0, 'left'), (0, 1, 'down'), (0, -1, 'up')):
            nx, ny, nm = x + dx, y + dy, m
            if not (0 <= nx < w and 0 <= ny < h):
                for cd, o, off in MAPS[m][3]:
                    if cd != d or o not in MAPS:
                        continue
                    ow, oh = MAPS[o][0], MAPS[o][1]
                    if d in ('left', 'right') and 0 <= y - off < oh:
                        nm, nx, ny = o, (ow - 1 if d == 'left' else 0), y - off; break
                    if d in ('up', 'down') and 0 <= x - off < ow:
                        nm, nx, ny = o, x - off, (oh - 1 if d == 'up' else 0); break
                else:
                    continue
            if (nm, nx, ny) not in seen and passable(grids[nm][ny][nx]):
                seen.add((nm, nx, ny)); q.append((nm, nx, ny))
    return seen

def fix_dims(name, w, h):      # register() never resizes an existing layout entry
    lp = os.path.join(REPO, 'data/layouts/layouts.json'); lj = json.load(open(lp))
    e = next(l for l in lj['layouts'] if l.get('id') == 'LAYOUT_' + snake_upper(name))
    if (e['width'], e['height']) != (w, h):
        e['width'], e['height'] = w, h
        open(lp, 'w').write(json.dumps(lj, indent=2, ensure_ascii=False) + '\n')

def main():
    ext = {}
    for src in {s[0] for s in SANDBARS.values()} | {o for m in MAPS.values() for _, o, _ in m[3] if o not in MAPS}:
        ext[src] = load(src)[3]
    grids = {}
    for n, (w, h, _, _) in MAPS.items():
        assert (w + 15) * (h + 14) <= 10240, n
        g = build(n, ext)
        for x, y, item, flag in DESIGN[n]['items']:
            assert (g[y][x] & 0x3FF) == 0x115 and passable(g[y][x]), (n, x, y, 'item not on sand')
        grids[n] = g
        write_bin(os.path.join(REPO, 'data/layouts', n, 'map.bin'), g)
        write_bin(os.path.join(REPO, 'data/layouts', n, 'border.bin'), [[BIG[0], BIG[1]], [BIG[2], BIG[3]]])
        md = os.path.join(REPO, 'data/maps', n); os.makedirs(md, exist_ok=True)
        open(os.path.join(md, 'map.json'), 'w').write(json.dumps(map_json(n), indent=2) + '\n')
        open(os.path.join(md, 'scripts.inc'), 'w').write(scripts(n))
        register('gMapGroup_TownsAndRoutes_Frlg', n, w, h, SECONDARY)
        fix_dims(n, w, h)
    for other, d, mine, off in EXTERNAL:
        add_connection(other, {'map': mid(mine), 'offset': off, 'direction': d})
    # reachability: every external seam cell that is open must be reachable from the Route 32 seam
    seen = reach(grids)
    for n, (w, h, _, conns) in MAPS.items():
        for d, o, off in conns:
            cells = [((0 if d == 'left' else w - 1), y) for y in range(h)] if d in ('left', 'right') else \
                    [(x, (0 if d == 'up' else h - 1)) for x in range(w)]
            ow, oh = (len(ext[o][0]), len(ext[o])) if o in ext else MAPS[o][:2]
            span = oh if d in ('left', 'right') else ow
            n_open = [(x, y) for x, y in cells if passable(grids[n][y][x]) and
                      0 <= (y if d in ('left', 'right') else x) - off < span]
            reached = [c for c in n_open if (n,) + c in seen]
            assert reached, (n, d, o, 'seam unreachable')
            print('  %s %s -> %s: %d open seam cells, %d reachable from a seed seam' % (n, d, o, len(n_open), len(reached)))
    wild()
    print('sea_route: %s; %d surfable cells reachable' % (', '.join('%s %dx%d' % (n, m[0], m[1]) for n, m in MAPS.items()), len(seen)))

if __name__ == '__main__':
    main()
