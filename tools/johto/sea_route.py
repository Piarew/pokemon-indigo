"""Custom water route: the VIOLET SEA ROUTE - a surf route from Violet City's south side (Route 32's sea) to the
southeast, joining the FireRed sea at Route 21 / Cinnabar Island.  Appended to run_all.sh; idempotent.

Violet City has no free edge (Route 31 / Route 36 / Route 32 / Mortar Trail), so the route starts on Route 32
(directly south of Violet), whose east edge rows 40-79 are open sea.  Three hand-laid maps
(gTileset_General_Frlg + gTileset_CinnabarIsland, FireRed sea metatiles only), placed so the world stays
geometrically consistent (coordinates relative to Violet City's top-left):
  SeaRouteVioletWest     100x70  x 20..119, y 76..145   left  <-> Route32 (its rows 40-79)
  SeaRouteVioletCentral   80x92  x120..199, y 70..161   up    <-> Route27 (its open south sea, cols 0-79)
  SeaRouteVioletEast      86x70  x201..286, y126..195   right <-> Route21_South (rows 0-49) + Cinnabar (rows 50-69)
Design: open water (0x12B) with the FireRed 2x2 water rocks (0x1CB/0x1CC/0x1D3/0x1D4) as a reef wall on every
edge that has no connection (so nothing opens into the border), rock reefs inside, and sandbars copied
tile-for-tile from Route 20 / Route 21.  Seam cells copy the neighbour's passability (rock where it is blocked).
Two item balls on sandbars (PEARL, BIG PEARL; FLAG_UNUSED_0x4A8/0x4A9).  Wild: Route 21's surf/fishing tables plus
GSC-flavoured extras.  A reachability check (BFS over surfable cells across the three maps) asserts that every
connection seam is reachable from Route 32.

JOHTO (regenerated by johto_convert, re-added here every run): Route32 right conn, Route27 down conn.
FIRERED EDITS (flagged; map.json connections only, no tile edits):
  CinnabarIsland_Frlg map.json : + connection left MAP_SEA_ROUTE_VIOLET_EAST offset -50
  Route21_South_Frlg  map.json : + connection left MAP_SEA_ROUTE_VIOLET_EAST offset 0
usage: python3 tools/johto/sea_route.py"""
