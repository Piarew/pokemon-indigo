#!/usr/bin/env python3
"""Second exits of Johto gatehouses (Phase 6).  Run after vrgate.py.
interiors.py builds each gate interior from an FRLG gate (kind 'nsgate' = Route5_SouthEntrance_Frlg: warps 0/2 south,
1/3 north) and points every exit at the outside door; this script re-points the far-side exits at the other map and
stamps the FRLG north-face gate entrance (Route5_Frlg rows 32-34, cols 22-27, General tileset) on that map.
Idempotent (the other map's layout is regenerated by johto_convert.py before this runs)."""
import json, os, struct
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(os.path.join(HERE, '..', '..'))

def blocks(path, w):
    d = open(os.path.join(REPO, path), 'rb').read(); v = list(struct.unpack('<%dH' % (len(d) // 2), d))
    return [v[i * w:(i + 1) * w] for i in range(len(v) // w)]

def save(path, g):
    with open(os.path.join(REPO, path), 'wb') as f:
        for r in g: f.write(struct.pack('<%dH' % len(r), *r))

def mj(name): return json.load(open(os.path.join(REPO, 'data/maps', name, 'map.json')))
def dump(name, j): open(os.path.join(REPO, 'data/maps', name, 'map.json'), 'w').write(json.dumps(j, indent=2, ensure_ascii=False) + '\n')

R5 = blocks('data/layouts/Route5_Frlg/map.bin', 48)
NFACE = [r[22:28] for r in R5[32:35]]            # door cells at facade cols 2,3 (Route5 x 24,25)

# gate interior, far map, (x0, y0) facade top-left on the far map, far-side interior warp ids
GATES = [('Route29_Route46Gate', 'Route46', 20, (5, 33), (1, 3))]

for gate, far, fw, (x0, y0), north in GATES:
    lp = 'data/layouts/%s/map.bin' % far
    g = blocks(lp, fw)
    for j, row in enumerate(NFACE):
        if y0 + j < len(g):
            g[y0 + j][x0:x0 + 6] = row
    save(lp, g)
    fj = mj(far); gj = mj(gate)
    gid = gj['id']
    old = [i for i, w in enumerate(fj['warp_events']) if w['dest_map'] == gid]
    base = old[0] if old else len(fj['warp_events'])   # replace in place (stable indices on re-runs)
    assert not old or old == list(range(base, base + len(north))), old
    for k, wid in enumerate(north):
        w = {'x': x0 + 2 + k, 'y': y0, 'elevation': 3, 'dest_map': gid, 'dest_warp_id': str(wid)}
        if old: fj['warp_events'][base + k] = w
        else: fj['warp_events'].append(w)
        gj['warp_events'][wid]['dest_map'] = fj['id']; gj['warp_events'][wid]['dest_warp_id'] = str(base + k)
    dump(far, fj); dump(gate, gj)
    print(gate, '<->', far, [(w['x'], w['y']) for w in fj['warp_events'][base:]])
